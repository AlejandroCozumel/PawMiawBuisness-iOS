#!/usr/bin/env python3
"""Writes PawMiawNegocios/Core/StringTables.swift: which strings table each
module file reads first (Modules/<Module>/X.swift -> <Module>.strings).
Run after adding or renaming a file in a module:  python3 scripts/strings-map.py
"""
import os, sys
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "PawMiawNegocios")
modules = os.path.join(root, "Modules")
rows = []
for module in sorted(os.listdir(modules)):
    folder = os.path.join(modules, module)
    if not os.path.isdir(folder):
        continue
    for dirpath, _, files in os.walk(folder):
        for name in sorted(files):
            if name.endswith(".swift"):
                rows.append((name, module))
names = [n for n, _ in rows]
dupes = sorted({n for n in names if names.count(n) > 1})
if dupes:
    sys.exit("Two module files share a name: " + ", ".join(dupes))
out = [
    "//",
    "//  StringTables.swift",
    "//  PawMiawNegocios",
    "//",
    "//  GENERATED by scripts/strings-map.py — do not edit by hand.",
    "//  Each module file reads its own <Module>.strings first, so the same",
    "//  English key can carry a different Spanish word in two modules.",
    "//",
    "",
    "enum StringTables {",
    "    static let moduleOfFile: [String: String] = [",
]
out += [f'        "{n}": "{m}",' for n, m in rows]
out += ["    ]", "}", ""]
open(os.path.join(root, "Core", "StringTables.swift"), "w").write("\n".join(out))
print(f"{len(rows)} files mapped")
